-- Run this in the Supabase SQL Editor to enable customer checkout and the admin Orders list.
-- Requires the public.profiles table created by this app's auth setup.

alter table public.profiles
  add column if not exists role text not null default 'customer';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_role_check'
      and conrelid = 'public.profiles'::regclass
  ) then
    alter table public.profiles
      add constraint profiles_role_check check (role in ('customer', 'admin'));
  end if;
end $$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

alter table public.products
  add column if not exists stock_quantity integer not null default 0;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'products_stock_quantity_check'
      and conrelid = 'public.products'::regclass
  ) then
    alter table public.products
      add constraint products_stock_quantity_check check (stock_quantity >= 0);
  end if;
end $$;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null,
  delivery_address text not null default '',
  fulfillment text not null check (fulfillment in ('delivery', 'pickup')),
  payment_method text not null check (payment_method in ('cod', 'gcash', 'card')),
  note text not null default '',
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  subtotal numeric(10,2) not null check (subtotal > 0),
  delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  total numeric(10,2) not null check (total = subtotal + delivery_fee),
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'preparing', 'ready', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  check (fulfillment = 'pickup' or length(trim(delivery_address)) > 0)
);

create index if not exists orders_user_created_idx
  on public.orders (user_id, created_at desc);
create index if not exists orders_created_idx
  on public.orders (created_at desc);

alter table public.orders enable row level security;
revoke all on public.orders from anon, public;
grant select, insert, update on public.orders to authenticated;

do $$
declare
  order_sequence text := pg_get_serial_sequence('public.orders', 'id');
begin
  if order_sequence is not null then
    execute format('revoke all on sequence %s from anon, public', order_sequence);
    execute format('grant usage, select on sequence %s to authenticated', order_sequence);
  end if;
end $$;

drop policy if exists "Customers can create their own orders" on public.orders;
create policy "Customers can create their own orders"
  on public.orders for insert to authenticated
  with check (user_id = (select auth.uid()) and status = 'pending');

drop policy if exists "Customers and admins can read orders" on public.orders;
create policy "Customers and admins can read orders"
  on public.orders for select to authenticated
  using (user_id = (select auth.uid()) or public.is_admin());

drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
  on public.orders for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create or replace function public.adjust_order_inventory()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  order_item jsonb;
  product_id bigint;
  quantity integer;
begin
  if tg_op = 'UPDATE' and old.status = new.status then
    return new;
  end if;

  if tg_op = 'UPDATE' and old.status <> 'cancelled' and new.status = 'cancelled' then
    for order_item in select value from jsonb_array_elements(old.items) loop
      product_id := (order_item ->> 'product_id')::bigint;
      quantity := (order_item ->> 'quantity')::integer;
      update public.products
        set stock_quantity = stock_quantity + quantity
        where id = product_id;
    end loop;
    return new;
  end if;

  if tg_op = 'INSERT' or (tg_op = 'UPDATE' and old.status = 'cancelled' and new.status <> 'cancelled') then
    for order_item in select value from jsonb_array_elements(new.items) loop
      product_id := (order_item ->> 'product_id')::bigint;
      quantity := (order_item ->> 'quantity')::integer;
      update public.products
        set stock_quantity = stock_quantity - quantity
        where id = product_id and available and stock_quantity >= quantity;
      if not found then
        raise exception 'Insufficient stock for product %', product_id using errcode = '23514';
      end if;
    end loop;
  end if;

  return new;
end;
$$;

revoke all on function public.adjust_order_inventory() from public;

drop trigger if exists adjust_inventory_for_order on public.orders;
create trigger adjust_inventory_for_order
  after insert or update of status on public.orders
  for each row execute function public.adjust_order_inventory();

